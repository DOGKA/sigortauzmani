-- Panel blog yönetimi.
-- 1) updated_at yalnızca okurun gördüğü metin değişince ilerler; kapak,
--    durum ya da sayaç güncellemesi "Güncellendi" tarihini oynatmaz.
-- 2) Betikle üretilen statik kapaklar featured_image alanına yazılır.

create or replace function public.blog_posts_set_updated_at() returns trigger
    language plpgsql
    as $$
begin
  if new.title is distinct from old.title
     or new.content is distinct from old.content
     or new.excerpt is distinct from old.excerpt then
    new.updated_at = now();
  end if;
  return new;
end;
$$;

